/*******************************************************************************
 * 文件   ：wdg_service.c
 * 功能   ：看门狗心跳服务实现
 * 说明   ：用 FreeRTOS 事件组收集各任务的心跳位；看门狗任务等“全部位到齐”，
 *          等齐后事件位自动清除，下一轮重新收集
 ******************************************************************************/

/* Includes ------------------------------------------------------------------*/
#include "wdg_service.h"
#include "FreeRTOS.h"
#include "event_groups.h"
#include "task.h"
#include <stddef.h>

/* Private variables ---------------------------------------------------------*/
static EventGroupHandle_t s_wdg_event = NULL;       // 心跳事件组

/* Exported functions --------------------------------------------------------*/

/*******************************************************************************
 * 函数名：wdg_service_init
 * 功  能：创建心跳事件组
 * 参  数：无
 * 返回值：true 表示创建成功，false 表示失败（内存不足）
 * 说  明：必须在启动调度器之前调用
 ******************************************************************************/
bool wdg_service_init(void)
{
    /*==============================
     *  #1. 创建事件组
     *==============================*/
    s_wdg_event = xEventGroupCreate();              // 从 FreeRTOS 堆分配

    return (s_wdg_event != NULL);                   // 返回创建结果
}

/*******************************************************************************
 * 函数名：wdg_kick
 * 功  能：上报某个任务的心跳
 * 参  数：bit —— 该任务对应的心跳位（WDG_BIT_xxx）
 * 返回值：无
 * 说  明：各任务在自己的周期循环里调用；非阻塞、可在任意上下文安全调用
 ******************************************************************************/
void wdg_kick(uint32_t bit)
{
    /*==============================
     *  #1. 置位对应心跳
     *==============================*/
    if (s_wdg_event != NULL)
    {
        (void)xEventGroupSetBits(s_wdg_event, bit); // 置位本任务的心跳
    }
}

/*******************************************************************************
 * 函数名：wdg_wait_all
 * 功  能：等待全部任务的心跳到齐
 * 参  数：无
 * 返回值：等到的心跳位集合（与 WDG_BIT_ALL 比较可判断是否齐全）
 * 说  明：等齐后事件位由内核自动清除，因此每轮都会重新收集
 ******************************************************************************/
uint32_t wdg_wait_all(void)
{
    EventBits_t bits;

    /*==============================
     *  #1. 未初始化则直接返回 0
     *==============================*/
    if (s_wdg_event == NULL)
    {
        return 0U;                                  // 事件组未创建
    }

    /*==============================
     *  #2. 等全部位（xWaitForAllBits = pdTRUE）
     *==============================*/
    bits = xEventGroupWaitBits(s_wdg_event,         // 事件组
                               WDG_BIT_ALL,         // 关心全部心跳位
                               pdTRUE,              // 等齐后清除
                               pdTRUE,              // 必须全部到齐
                               pdMS_TO_TICKS(WDG_WAIT_TIMEOUT_MS));  // 超时

    return (uint32_t)bits;                          // 返回到位情况
}
