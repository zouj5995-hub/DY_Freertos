/*******************************************************************************
 * 文件   ：sense.h
 * 功能   ：模拟量采集层对外接口（电压、三路温度）
 * 说明   ：本层只负责“把 ADC 原始值变成工程值”，不做任何判断；
 *          判断（阈值告警）属于监控任务的职责
 ******************************************************************************/
#ifndef __SENSE_H
#define __SENSE_H


/* Includes ------------------------------------------------------------------*/
#include <stdint.h>

/* Exported types ------------------------------------------------------------*/

/*******************************************************************************
 * 名称  ：sense_data_t
 * 功能  ：一次采集到的全部模拟量
 * 说明  ：一次读完所有量，避免多次调用时数据不同步
 ******************************************************************************/
typedef struct
{
    float voltage;      // 电池电压（V）
    float temp_env;     // 环境温度（℃）
    float temp_ipc;     // 工控机散热鳍片温度（℃）
    float temp_pcb;     // 电源板温度（℃）
} sense_data_t;

/* Exported functions prototypes ---------------------------------------------*/

/*******************************************************************************
 * 函数名：sense_read_all
 * 功  能：采集并换算全部模拟量
 * 参  数：d —— 输出结构体指针
 * 返回值：无
 * 说  明：内部为阻塞式 ADC 转换，请在低优先级任务中调用
 ******************************************************************************/
void sense_read_all(sense_data_t *d);


#endif /* __SENSE_H */