/*******************************************************************************
 * 文件   ：task_wdg.c
 * 功能   ：看门狗任务——只有全部任务心跳到齐才喂狗
 * 说明   ：这是“心跳式看门狗”：普通看门狗只要主循环还在转就会喂，
 *          而本实现要求每个参与监控的任务都活着；
 *          任一任务卡死 → 不再喂狗 → IWDG 超时（4 秒）复位系统
 ******************************************************************************/

/* Includes ------------------------------------------------------------------*/
#include "tasks.h"
#include "wdg_service.h"
#include "log.h"
#include "iwdg.h"
#include "FreeRTOS.h"
#include "task.h"

/* Private define ------------------------------------------------------------*/
#define WDG_PERIOD_MS   1000U       // 喂狗检查周期（毫秒）

/* Exported functions --------------------------------------------------------*/

/*******************************************************************************
 * 函数名：TaskWdg
 * 功  能：看门狗任务主体：等全部心跳 → 齐全则喂狗，缺失则不喂并记录
 * 参  数：argument —— 创建任务时传入的参数，本任务不使用
 * 返回值：无（永不返回）
 * 说  明：调试模式（WDG_ENABLE = 0）时无条件喂狗，便于单步调试
 ******************************************************************************/
void TaskWdg(void *argument)
{
    TickType_t last_wake_tick = xTaskGetTickCount();    // 记录周期起点
    uint32_t   miss_count     = 0U;                     // 连续缺心跳次数

    /*==============================
     *  #1. 任务主循环（永不退出）
     *==============================*/
    for (;;)
    {
#if (WDG_ENABLE == 1)
        /*==============================
         *  #2. 等全部任务心跳（超时时间小于 IWDG 超时）
         *==============================*/
        uint32_t bits = wdg_wait_all();

        /*==============================
         *  #3. 心跳齐全才喂狗
         *==============================*/
        if ((bits & WDG_BIT_ALL) == WDG_BIT_ALL)
        {
            (void)HAL_IWDG_Refresh(&hiwdg);             // 喂狗
            miss_count = 0U;                            // 清零缺失计数
        }
        else
        {
            miss_count++;                               // 累计缺失次数

            LOG_ERROR("看门狗：任务心跳缺失（到位 0x%02lX，应为 0x%02lX），第 %lu 次，不再喂狗",
                      (unsigned long)bits,
                      (unsigned long)WDG_BIT_ALL,
                      (unsigned long)miss_count);
        }
#else
        /*==============================
         *  #4. 调试模式：无条件喂狗
         *==============================*/
        (void)HAL_IWDG_Refresh(&hiwdg);                 // 不检查心跳，避免调试被复位
#endif

        /*==============================
         *  #5. 等到下一个检查周期
         *==============================*/
        vTaskDelayUntil(&last_wake_tick, pdMS_TO_TICKS(WDG_PERIOD_MS));
    }
}
